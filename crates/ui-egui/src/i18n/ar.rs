//! Arabic translations for the interface strings in i18n.rs.

use std::collections::HashMap;
use std::sync::LazyLock;

static CATALOG: LazyLock<HashMap<&'static str, &'static str>> = LazyLock::new(|| {
    let mut m = HashMap::with_capacity(TABLE.len());
    for &(key, val) in TABLE {
        let vis: &'static str = Box::leak(crate::i18n::bidi::visual(val).into_boxed_str());
        m.insert(key, vis);
    }
    m
});

pub(super) fn translate(text: &str) -> Option<&'static str> {
    CATALOG.get(text).copied()
}

